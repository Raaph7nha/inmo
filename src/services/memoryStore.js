export const memoryStore = {
  getAllViviendas() {
    return SEED_VIVIENDAS;
  },
  getViviendaById(id) {
    return SEED_VIVIENDAS.find((v) => v.id === Number(id)) || null;
  },
  getViviendasByIds(ids) {
    return ids.map((id) => SEED_VIVIENDAS.find((v) => v.id === Number(id))).filter(Boolean);
  },
  getBarriosResumen() {
    const map = new Map();
    for (const item of SEED_VIVIENDAS) {
      if (item.activo === false) continue;
      const loc = item.localidad;
      if (!loc) continue;
      if (!map.has(loc)) {
        map.set(loc, { nombre: loc, localidad: loc, total: 0 });
      }
      map.get(loc).total += 1;
    }
    return Array.from(map.values()).sort((a, b) => b.total - a.total);
  },
  getGuardadosIds(usuarioId) {
    return [...(guardadosMap.get(usuarioId) || [])];
  },
  addGuardado(usuarioId, viviendaId) {
    const list = guardadosMap.get(usuarioId) || [];
    if (!list.includes(viviendaId)) {
      list.unshift(viviendaId);
      guardadosMap.set(usuarioId, list);
    }
    return [...list];
  },
  removeGuardado(usuarioId, viviendaId) {
    const list = (guardadosMap.get(usuarioId) || []).filter((id) => id !== Number(viviendaId));
    guardadosMap.set(usuarioId, list);
    return [...list];
  },
  getComparadorIds(usuarioId) {
    return [...(comparadorMap.get(usuarioId) || [])];
  },
  addComparador(usuarioId, viviendaId) {
    const list = comparadorMap.get(usuarioId) || [];
    if (list.includes(viviendaId)) return { status: 200, ids: [...list] };
    if (list.length >= 3) {
      throw new AppError('Solo puedes comparar hasta 3 inmuebles simultáneos.', 400, 'COMPARE_LIMIT_REACHED');
    }
    list.push(viviendaId);
    comparadorMap.set(usuarioId, list);
    return { status: 201, ids: [...list] };
  },
  removeComparador(usuarioId, viviendaId) {
    const list = (comparadorMap.get(usuarioId) || []).filter((id) => id !== Number(viviendaId));
    comparadorMap.set(usuarioId, list);
    return [...list];
  },
  clearComparador(usuarioId) {
    comparadorMap.set(usuarioId, []);
    return [];
  }
};
